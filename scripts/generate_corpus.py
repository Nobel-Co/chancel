def write_corpus(
    out_dir: Path, seed: int = 1789, pad_matter: str | None = None, pad_count: int = 0
) -> dict:
    """
    Generate synthetic corpus and write to disk.

    Args:
        out_dir: Directory to write corpus files
        seed: Random seed for deterministic generation
        pad_matter: Matter to pad with extra documents (matter-alderman or
            matter-brightwater)
        pad_count: Number of padding documents to add

    Returns:
        Manifest dict with metadata
    """
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    corpus = generate(seed)

    # Add padding documents if requested
    if pad_matter and pad_count > 0:
        if pad_matter not in corpus:
            raise ValueError(f"Unknown matter: {pad_matter}")

        rng = random.Random(seed)
        # Deterministic vocabulary skew per matter
        if pad_matter == "matter-alderman":
            vocab = [
                "demurrage",
                "fumigation",
                "phytosanitary",
                "containerized",
                "manifest",
                "port authority",
                "cargo",
                "contamination",
                "quarantine",
                "inspection",
                "shipper",
                "consignee",
                "customs",
                "bill of lading",
                "freight forwarding",
            ]
        else:  # matter-brightwater
            vocab = [
                "subrogation",
                "salvage award",
                "seaworthiness",
                "hull",
                "marine casualty",
                "underwriter",
                "policy limit",
                "deductible",
                "coverage",
                "claim",
                "insurable interest",
                "abandonment",
                "average",
                "wreck",
                "recovery",
            ]

        base_count = len(corpus[pad_matter])
        for i in range(pad_count):
            doc_id = f"{pad_matter[7]}{base_count + i + 1}"
            # Generate filler text using vocabulary
            vocab_sample = rng.choices(vocab, k=8)
            text = (
                f"Filler document for padding purposes. Discussion of "
                f"{', '.join(vocab_sample)}. This document is generated deterministically "
                f"for statistical testing and contains no substantive content related to "
                f"the matter."
            )

            corpus[pad_matter].append(
                {
                    "local_id": doc_id,
                    "scope": "space",
                    "space_id": pad_matter,
                    "title": f"Filler Document {i + 1}",
                    "text": text,
                }
            )

    # Generate canaries
    canaries = {}
    for matter in ["alderman", "brightwater"]:
        canary = (
            f"CANARY-{matter.upper()}-"
            f"{hashlib.sha256(f'{seed}:{matter}'.encode()).hexdigest()[:12]}"
        )
        canaries[f"matter-{matter}"] = canary

    # Write JSONL files
    manifest = {"seed": seed, "doc_counts": {}, "file_hashes": {}}

    for corpus_name, docs in corpus.items():
        filename = f"{corpus_name}.jsonl"
        filepath = out_dir / filename

        with open(filepath, "w") as f:
            for doc in docs:
                f.write(json.dumps(doc) + "\n")

        # Compute hash
        with open(filepath, "rb") as f:
            file_hash = hashlib.sha256(f.read()).hexdigest()

        manifest["doc_counts"][corpus_name] = len(docs)
        manifest["file_hashes"][corpus_name] = file_hash

    # Write canaries.json
    canaries_path = out_dir / "canaries.json"
    with open(canaries_path, "w") as f:
        json.dump(canaries, f, indent=2)

    # Write manifest.json
    manifest_path = out_dir / "manifest.json"
    with open(manifest_path, "w") as f:
        json.dump(manifest, f, indent=2)

    return manifest


